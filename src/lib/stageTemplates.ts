export function formatSubstepName(s: StageTemplateSubstep) {
  return s.group ? `${s.group} · ${s.name}` : s.name;
}

export function defaultStagesWithSubsteps() {
  return STAGE_TEMPLATES.map((t, i) => ({
    id: i + 1,
    name: t.name,
    order_index: i,
    substeps: t.substeps.map((s, j) => ({
      id: j + 1,
      name: formatSubstepName(s),
      order_index: j,
    })),
  }));
}

/** Legacy name → current template name */
export function normalizeTemplateStageName(name: string) {
  const n = name.trim().replace(/\s+/g, " ");
  if (/^объект\s+заверш[её]н[аоы]?$/i.test(n)) return "Сдача и приёмка";
  if (/^электрика\s+и\s+сантехника$/i.test(n)) return "Инженерные системы";
  return n;
}
